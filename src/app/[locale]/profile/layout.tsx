import { SIGNIN_ROUTE } from "@/config/routes";
import { redirect } from "@/i18n/routing";
import { auth } from "@/lib/auth";
import { SidebarInset, SidebarProvider } from "@/components/ui/sidebar";
import { Metadata } from "next";
import { headers } from "next/headers";
import React from "react";
import { AppSidebar, GridBg } from "@/features/layout";
import { SiteHeader } from "@/features/layout";
import { UserRole } from "@prisma/client";

export const metadata: Metadata = {
	title: "Profile",
	description: "Generated by create next app",
};

const ProfileLayout = async ({
	children,
	params,
}: {
	children: React.ReactNode;
	params: { locale: string };
}) => {
	const { locale } = await params;

	const h = await headers();

	let sessionRaw: Awaited<ReturnType<typeof auth.api.getSession>> | null =
		null;
	try {
		sessionRaw = await auth.api.getSession({ headers: h });
	} catch (e) {
		// DB / network error — do NOT treat this as "no session".
		// Let Next.js render the error boundary instead of logging the user out.
		console.error("getSession error:", e);
		throw e;
	}

	if (!sessionRaw?.user) {
		redirect({ href: SIGNIN_ROUTE, locale });
		return null;
	}

	return (
		<SidebarProvider>
			<AppSidebar
				user={{
					...sessionRaw.user,
					role: sessionRaw.user.role ?? UserRole.USER,
				}}
			/>
			<SidebarInset className="sidebar-inset rounded-none md:rounded-2xl! overflow-clip border border-border shadow-lg!">
				<SiteHeader />
				<main className="profile-layout relative flex flex-1 flex-col gap-4 p-4 px-5 rounded-xl h-full overflow-y-auto">
					<GridBg className="opacity-0 xl:opacity-50 2xl:opacity-100" />
					<div className="container max-w-6xl mx-auto z-10">
						{children}
					</div>
				</main>
			</SidebarInset>
		</SidebarProvider>
		// <div className="[--header-height:calc(--spacing(14))]">
		// 	<SidebarProvider className="flex flex-col">
		// 		<div className="flex flex-1">
		// 			<AppSidebar
		// 				user={{
		// 					...sessionRaw.user,
		// 					role: sessionRaw.user.role ?? UserRole.USER,
		// 				}}
		// 			/>
		// 			<SidebarInset className="h-full overflow-hidden">
		// 				<SiteHeader />
		// 				<main className="profile-layout flex flex-1 flex-col gap-4 p-4 px-5">
		// 					{children}
		// 				</main>
		// 			</SidebarInset>
		// 		</div>
		// 	</SidebarProvider>

		// 	<MobileMenu />
		// </div>
	);
};

export default ProfileLayout;
